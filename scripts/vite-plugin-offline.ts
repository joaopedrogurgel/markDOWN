import type { Plugin } from 'vite';

/**
 * Generates `sw.js`, a service worker that precaches every file of the build so
 * the app works offline after the first visit. Hashed assets never change, so
 * they are served from the cache; the page itself is fetched from the network
 * first, so a new deploy shows up as soon as there is a connection.
 */
export function offline(): Plugin {
  let base = '/';
  return {
    name: 'markdown-offline',
    apply: 'build',
    configResolved(config) {
      base = config.base;
    },
    generateBundle(_options, bundle) {
      const files = Object.keys(bundle).filter((file) => !file.endsWith('.map'));
      const extra = [
        '',
        'manifest.webmanifest',
        'favicon.svg',
        'exemplo.pdf',
        'icons/icon-192.png',
        'icons/icon-512.png',
      ];
      const urls = [...new Set([...extra, ...files])].map((file) => base + file);
      const version = Date.now().toString(36);
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: serviceWorker(version, base, urls) });
    },
  };
}

const serviceWorker = (
  version: string,
  base: string,
  urls: string[],
) => `// Generated by scripts/vite-plugin-offline.ts at build time.
const CACHE = 'markdown-${version}';
const BASE = ${JSON.stringify(base)};
const PRECACHE = ${JSON.stringify(urls)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key.startsWith('markdown-') && key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;

  if (request.mode === 'navigate') {
    // Network first for the page, so new deploys arrive; the cached page when offline.
    event.respondWith(
      fetch(request)
        .then((response) => {
          const copy = response.clone();
          caches.open(CACHE).then((cache) => cache.put(BASE, copy));
          return response;
        })
        .catch(() => caches.match(BASE, { ignoreVary: true })),
    );
    return;
  }

  // Cache first for everything else: built files have content hashes in their names.
  // ignoreVary: some servers add "Vary: Origin", which would hide cached module scripts.
  event.respondWith(caches.match(request, { ignoreVary: true }).then((cached) => cached ?? fetch(request)));
});
`;
